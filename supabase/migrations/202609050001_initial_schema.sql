-- BingeTrail MVP schema. TMDB remains the source of catalog metadata.

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text check (char_length(display_name) between 1 and 40),
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.user_media (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  tmdb_id integer not null check (tmdb_id > 0),
  media_type text not null check (media_type in ('movie', 'series')),
  status text not null check (status in ('planned', 'watching', 'completed', 'paused', 'dropped')),
  progress_percent numeric(5, 2) not null default 0 check (progress_percent between 0 and 100),
  last_watched_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, tmdb_id, media_type)
);

create table public.episode_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  tmdb_show_id integer not null check (tmdb_show_id > 0),
  season_number integer not null check (season_number >= 0),
  episode_number integer not null check (episode_number > 0),
  watched_at timestamptz not null default now(),
  unique (user_id, tmdb_show_id, season_number, episode_number)
);

create table public.custom_lists (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  description text check (char_length(description) <= 500),
  is_public boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.list_items (
  id bigint generated by default as identity primary key,
  list_id uuid not null references public.custom_lists (id) on delete cascade,
  tmdb_id integer not null check (tmdb_id > 0),
  media_type text not null check (media_type in ('movie', 'series')),
  position integer not null default 0 check (position >= 0),
  added_at timestamptz not null default now(),
  unique (list_id, tmdb_id, media_type)
);

create table public.ratings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  tmdb_id integer not null check (tmdb_id > 0),
  media_type text not null check (media_type in ('movie', 'series', 'episode')),
  season_number integer check (season_number >= 0),
  episode_number integer check (episode_number > 0),
  score numeric(3, 1) not null check (score between 0.5 and 10),
  note text check (char_length(note) <= 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index user_media_user_status_idx on public.user_media (user_id, status);
create index episode_progress_user_show_idx on public.episode_progress (user_id, tmdb_show_id);
create index custom_lists_user_idx on public.custom_lists (user_id);
create index list_items_list_position_idx on public.list_items (list_id, position);
create index ratings_user_idx on public.ratings (user_id);

alter table public.profiles enable row level security;
alter table public.user_media enable row level security;
alter table public.episode_progress enable row level security;
alter table public.custom_lists enable row level security;
alter table public.list_items enable row level security;
alter table public.ratings enable row level security;

create policy "Users manage their own profile"
on public.profiles for all
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

create policy "Users manage their own media"
on public.user_media for all
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "Users manage their own episode progress"
on public.episode_progress for all
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "Users manage their own lists"
on public.custom_lists for all
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "Users manage items in their own lists"
on public.list_items for all
using (
  exists (
    select 1 from public.custom_lists
    where custom_lists.id = list_items.list_id
      and custom_lists.user_id = (select auth.uid())
  )
)
with check (
  exists (
    select 1 from public.custom_lists
    where custom_lists.id = list_items.list_id
      and custom_lists.user_id = (select auth.uid())
  )
);

create policy "Users manage their own ratings"
on public.ratings for all
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', 'BingeTrail user'));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();
